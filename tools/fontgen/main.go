// Command fontgen converts tinyfont fonts to romfont fonts (glyphs in
// strings, so TinyGo keeps them in flash). It writes the fonts this
// repository uses:
//
//	go run ./tools/fontgen   (or: go generate ./romfont)
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"

	"tinygo.org/x/tinyfont"
	"tinygo.org/x/tinyfont/freesans"
	"tinygo.org/x/tinyfont/proggy"
)

type font struct {
	name string
	f    *tinyfont.Font
}

var packages = []struct {
	name  string
	fonts []font
}{
	{"freesans", []font{
		{"Bold9pt7b", &freesans.Bold9pt7b},
		{"Bold12pt7b", &freesans.Bold12pt7b},
		{"Bold18pt7b", &freesans.Bold18pt7b},
		{"Bold24pt7b", &freesans.Bold24pt7b},
		{"Regular9pt7b", &freesans.Regular9pt7b},
	}},
	{"proggy", []font{
		{"TinySZ8pt7b", &proggy.TinySZ8pt7b},
	}},
}

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	for _, p := range packages {
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by tools/fontgen from tinygo.org/x/tinyfont/%s. DO NOT EDIT.\n\n", p.name)
		fmt.Fprintf(&b, "// Package %s has the tinyfont %s fonts as romfont fonts (in flash).\n", p.name, p.name)
		fmt.Fprintf(&b, "package %s\n\nimport \"github.com/sat0ken/tinygo-cyd/romfont\"\n", p.name)
		for _, f := range p.fonts {
			index, data := convert(f.f)
			fmt.Fprintf(&b, "\nvar %s = romfont.Font{\n\tYAdvance: %d,\n\tIndex: %s,\n\tData: %s,\n}\n",
				f.name, f.f.YAdvance, literal(index), literal(data))
		}
		src, err := format.Source(b.Bytes())
		if err != nil {
			log.Fatal(err)
		}
		dir := filepath.Join(root, "romfont", p.name)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, "fonts.go"), src, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

func convert(f *tinyfont.Font) (index, data []byte) {
	glyphs := append([]tinyfont.Glyph(nil), f.Glyphs...)
	sort.Slice(glyphs, func(i, j int) bool { return glyphs[i].Rune < glyphs[j].Rune })
	for _, g := range glyphs {
		off := len(data)
		if off >= 1<<24 || g.Rune >= 1<<24 {
			log.Fatal("font too large")
		}
		index = append(index, byte(g.Rune>>16), byte(g.Rune>>8), byte(g.Rune), byte(off>>16), byte(off>>8), byte(off))
		data = append(data, g.Width, g.Height, g.XAdvance, byte(g.XOffset), byte(g.YOffset))
		data = append(data, g.Bitmaps...)
	}
	return
}

// literal writes b as a string literal in lines of 32 bytes.
func literal(b []byte) string {
	if len(b) == 0 {
		return `""`
	}
	var s bytes.Buffer
	for i := 0; i < len(b); i += 32 {
		if i > 0 {
			s.WriteString(" +\n\t\t")
		}
		s.WriteByte('"')
		for _, c := range b[i:min(i+32, len(b))] {
			fmt.Fprintf(&s, "\\x%02x", c)
		}
		s.WriteByte('"')
	}
	return s.String()
}
