// Command picoimg converts the C arrays of PicoLibSDK (images, palettes and
// fonts written by its PicoPadImg and RaspPicoImg tools, e.g.
// PicoPad/GAME/TETRIS/img/tiles.cpp) to Go string constants, which TinyGo
// keeps in flash. The bytes stay as they are, so the drawing functions of
// package picopad read them like PicoLibSDK does; u16 arrays (palettes) are
// written little endian.
//
// The constants are named after the arrays, with the first letter in lower
// case and without underscores (TilesImg_Pal -> tilesImgPal). The comment
// before an array ("// format: 8-bit paletted pixel graphics" ...) is kept.
//
// With -embed dir, the arrays of 1 KB or more are written to dir (next to
// the output file) as name.bin and become string variables with
// //go:embed: TinyGo keeps them in flash as well, and the repository holds
// the bytes instead of four characters each.
//
//	go run ./tools/picoimg -pkg tetris -root ~/PicoLibSDK -o games/tetris/tiles.go PicoPad/GAME/TETRIS/img/tiles.cpp
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// array matches one array with the comment lines before it.
var array = regexp.MustCompile(`(?ms)((?:^//[^\n]*\n)*)^const\s+(u8|s8|u16)\s+(\w+)\s*\[\s*\d*\s*\][^=]*=\s*\{(.*?)\}\s*;`)

type constant struct {
	comment []string
	name    string
	data    []byte
}

func main() {
	pkg := flag.String("pkg", "", "package of the output file")
	root := flag.String("root", ".", "the PicoLibSDK directory the input paths are relative to")
	out := flag.String("o", "", "output file")
	embed := flag.String("embed", "", "directory (next to the output file) for the large arrays, embedded with //go:embed")
	flag.Parse()
	if *pkg == "" || *out == "" || flag.NArg() == 0 {
		log.Fatal("usage: picoimg -pkg name [-root dir] -o out.go file.cpp...")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/picoimg from PicoLibSDK %s. DO NOT EDIT.\n\n", strings.Join(flag.Args(), ", "))
	fmt.Fprintf(&b, "package %s\n", *pkg)
	if *embed != "" {
		fmt.Fprintf(&b, "\nimport _ \"embed\"\n")
		if err := os.MkdirAll(filepath.Join(filepath.Dir(*out), *embed), 0o755); err != nil {
			log.Fatal(err)
		}
	}
	for _, name := range flag.Args() {
		src, err := os.ReadFile(filepath.Join(*root, name))
		if err != nil {
			log.Fatal(err)
		}
		cs, err := parse(src)
		if err != nil {
			log.Fatalf("%s: %v", name, err)
		}
		for _, c := range cs {
			b.WriteByte('\n')
			for _, l := range c.comment {
				fmt.Fprintf(&b, "%s\n", l)
			}
			if *embed != "" && len(c.data) >= 1024 {
				file := filepath.Join(*embed, c.name+".bin")
				if err := os.WriteFile(filepath.Join(filepath.Dir(*out), file), c.data, 0o644); err != nil {
					log.Fatal(err)
				}
				fmt.Fprintf(&b, "//\n//go:embed %s\nvar %s string\n", filepath.ToSlash(file), c.name)
				continue
			}
			fmt.Fprintf(&b, "const %s = %s\n", c.name, literal(c.data))
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// parse returns the arrays of a C source file.
func parse(src []byte) ([]constant, error) {
	src = bytes.ReplaceAll(src, []byte("\r\n"), []byte("\n"))
	var cs []constant
	for _, m := range array.FindAllSubmatch(src, -1) {
		c := constant{name: goName(string(m[3]))}
		for _, l := range strings.Split(strings.TrimSpace(string(m[1])), "\n") {
			if l != "" {
				c.comment = append(c.comment, l)
			}
		}
		for _, f := range strings.FieldsFunc(string(m[4]), func(r rune) bool { return r == ',' || r <= ' ' }) {
			v, err := strconv.ParseInt(f, 0, 32)
			if err != nil {
				return nil, fmt.Errorf("%s: %v", m[3], err)
			}
			switch string(m[2]) {
			case "u16":
				if v < 0 || v > 0xFFFF {
					return nil, fmt.Errorf("%s: %s is not a u16", m[3], f)
				}
				c.data = append(c.data, byte(v), byte(v>>8))
			default:
				if v < -128 || v > 0xFF {
					return nil, fmt.Errorf("%s: %s is not a byte", m[3], f)
				}
				c.data = append(c.data, byte(v))
			}
		}
		cs = append(cs, c)
	}
	if len(cs) == 0 {
		return nil, fmt.Errorf("no arrays found")
	}
	return cs, nil
}

// goName turns a C name into an unexported Go name: TilesImg_Pal ->
// tilesImgPal.
func goName(s string) string {
	s = strings.ReplaceAll(s, "_", "")
	return strings.ToLower(s[:1]) + s[1:]
}

// literal writes b as a string literal in lines of 32 bytes.
func literal(b []byte) string {
	if len(b) == 0 {
		return `""`
	}
	var s bytes.Buffer
	for i := 0; i < len(b); i += 32 {
		if i > 0 {
			s.WriteString(" +\n\t")
		}
		s.WriteByte('"')
		for _, c := range b[i:min(i+32, len(b))] {
			fmt.Fprintf(&s, "\\x%02x", c)
		}
		s.WriteByte('"')
	}
	return s.String()
}
