#!/usr/bin/env python3
"""Writes games/mahjong/font_data.go: the glyphs of the Japanese characters in
the strings of the package, 8 x 8 from Misaki Gothic and 16 x 16 from Shinonome.
Run it after adding a new character. The fonts are not in this repository:

    https://littlelimit.net/arc/misaki/misaki_bdf_2021-05-05.zip
        misaki_gothic.bdf (free to use, change and share, no warranty)
    http://openlab.ring.gr.jp/efont/dist/shinonome/shinonome-0.9.11p1.tar.bz2
        bdf/shnmk16.bdf, bdf/shnm8x16a.bdf (in effect public domain)

    python3 tools/jpfontgen/gen.py misaki_gothic.bdf shnmk16.bdf shnm8x16a.bdf
"""
import glob
import os
import re
import sys

PKG = "games/mahjong"
ASCII = "+-0123456789?"


def read_bdf(path):
    """Returns {encoding: (rows as ints, BBX)}."""
    font = {}
    enc, bbx, rows = 0, (0, 0, 0, 0), None
    for line in open(path, encoding="latin1"):
        line = line.strip()
        if line.startswith("ENCODING "):
            enc = int(line.split()[1])
        elif line.startswith("BBX "):
            bbx = tuple(int(v) for v in line.split()[1:])
        elif line == "BITMAP":
            rows = []
        elif line == "ENDCHAR":
            font[enc] = (rows, bbx)
            rows = None
        elif rows is not None:
            rows.append(line)
    return font


def jis(c):
    b = c.encode("euc_jp")
    return (b[0] - 0x80) << 8 | (b[1] - 0x80)


def small(font, c):
    """Eight bytes: the cell's lowest row is one below the baseline."""
    hexrows, (_, h, xoff, yoff) = font[ord(c)]
    cell = [0] * 8
    top = 6 - (yoff + h - 1)
    for j, row in enumerate(hexrows):
        cell[top + j] = int(row, 16) >> xoff
    return bytes(cell)


def big(font, code, width):
    """Sixteen rows of width/8 bytes."""
    hexrows, _ = font[code]
    if len(hexrows) != 16:
        sys.exit(f"{code:#x}: {len(hexrows)} rows")
    return b"".join(bytes.fromhex(row) for row in hexrows)


def used_runes():
    runes = set()
    for name in glob.glob(os.path.join(PKG, "*.go")):
        if name.endswith("_test.go") or name.endswith("font_data.go"):
            continue
        for line in open(name, encoding="utf-8"):
            line = re.sub(r'(^|\s)//.*$', "", line)
            for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', line):
                runes.update(c for c in lit if ord(c) >= 0x80)
    return sorted(runes)


def go_string(b):
    return '"' + "".join(f"\\x{v:02x}" for v in b) + '"'


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    misaki, kanji, latin = (read_bdf(p) for p in sys.argv[1:])
    runes = used_runes()
    out = ["// Code generated by tools/jpfontgen. DO NOT EDIT.\n", "package mahjong\n"]
    out.append("// The characters in the fonts, in order.\nvar fontRunes = [...]uint16{")
    out += [f"\t0x{ord(c):04X}, // {c}" for c in runes]
    out.append("}\n")
    out.append("// Eight rows for each character (Misaki Gothic); in strings, so that the\n"
               "// glyphs stay in flash.\nconst fontSmall = \"\" +")
    out += [f"\t{go_string(small(misaki, c))}{' +' if i < len(runes) - 1 else ''} // {c}" for i, c in enumerate(runes)]
    out.append("")
    out.append("// Sixteen rows of two bytes for each character (Shinonome).\nconst fontBig = \"\" +")
    out += [f"\t{go_string(big(kanji, jis(c), 16))}{' +' if i < len(runes) - 1 else ''} // {c}" for i, c in enumerate(runes)]
    out.append("")
    out.append(f"// The signs and digits of the large text, sixteen rows of one byte each.\nconst bigASCII = {ASCII!r}\n".replace("'", '"'))
    out.append("const fontBigASCII = \"\" +")
    out += [f"\t{go_string(big(latin, ord(c), 8))}{' +' if i < len(ASCII) - 1 else ''} // {c}" for i, c in enumerate(ASCII)]
    with open(os.path.join(PKG, "font_data.go"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(len(runes), "characters")


main()
