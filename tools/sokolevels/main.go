// Command sokolevels converts the level files of PicoLibSDK's SOKOBAN
// (PicoPad/GAME/SOKOBAN/src/levels_*.cpp) to Go for package
// games/sokoban. Each C array of levels (the definition and the solution
// of each level) becomes a string constant, which TinyGo keeps in flash:
// a definition and a solution a line each, every line ending with "\n".
// The collections (sCollect) become an array of collect. The comments of
// the file before the levels (the author and the license) are kept as
// they are, so are the comments before the arrays and the levels.
//
//	go run ./tools/sokolevels -pkg sokoban -root ~/PicoLibSDK -o games/sokoban/levels_damgaard.go PicoPad/GAME/SOKOBAN/src/levels_damgaard.cpp
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var (
	levelArray = regexp.MustCompile(`(?ms)((?:^//[^\n]*\n)*)^const char\* const (\w+)\[\] = \{(.*?)\n\};`)
	collArray  = regexp.MustCompile(`(?ms)^const sCollect (\w+)\[\] = \{(.*?)\n\};`)
	collEntry  = regexp.MustCompile(`\{\s*"([^"]*)",\s*(\w+),\s*count_of\(\w+\)/2\s*\}`)
)

func main() {
	pkg := flag.String("pkg", "", "package of the output file")
	root := flag.String("root", ".", "the PicoLibSDK directory the input path is relative to")
	out := flag.String("o", "", "output file")
	flag.Parse()
	if *pkg == "" || *out == "" || flag.NArg() != 1 {
		log.Fatal("usage: sokolevels -pkg name [-root dir] -o out.go levels_name.cpp")
	}
	raw, err := os.ReadFile(filepath.Join(*root, flag.Arg(0)))
	if err != nil {
		log.Fatal(err)
	}
	src, err := convert(latin1(raw), flag.Arg(0), *pkg)
	if err != nil {
		log.Fatalf("%s: %v", flag.Arg(0), err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// latin1 returns the file as UTF-8, reading bytes above 0x7F as Latin-1
// (the © of a copyright line) and dropping carriage returns.
func latin1(b []byte) string {
	var s strings.Builder
	for _, c := range b {
		if c != '\r' {
			s.WriteRune(rune(c))
		}
	}
	return s.String()
}

// goName lowers the first letter (DamgaardCol1 -> damgaardCol1).
func goName(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func convert(s, name, pkg string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/sokolevels from PicoLibSDK %s. DO NOT EDIT.\n\n", name)

	// the comments before #include: the author and the license
	inc := strings.Index(s, "#include")
	if inc < 0 {
		return nil, fmt.Errorf("no #include")
	}
	for _, l := range strings.Split(s[:inc], "\n") {
		if l = strings.TrimRight(l, " \t"); strings.HasPrefix(l, "//") {
			b.WriteString(l + "\n")
		}
	}
	fmt.Fprintf(&b, "\npackage %s\n", pkg)

	counts := map[string]int{}
	for _, m := range levelArray.FindAllStringSubmatch(s, -1) {
		items, err := parseItems(m[3])
		if err != nil {
			return nil, fmt.Errorf("%s: %v", m[2], err)
		}
		if len(items)%2 != 0 {
			return nil, fmt.Errorf("%s: %d strings, not a definition and a solution each", m[2], len(items))
		}
		counts[m[2]] = len(items) / 2
		b.WriteString("\n" + m[1])
		fmt.Fprintf(&b, "const %s = \"\" +\n", goName(m[2]))
		for k, it := range items {
			for _, c := range it.comments {
				b.WriteString("\t" + c + "\n")
			}
			for j, p := range it.pieces {
				if j == len(it.pieces)-1 {
					p += "\n"
				}
				end := " +"
				if k == len(items)-1 && j == len(it.pieces)-1 {
					end = ""
				}
				fmt.Fprintf(&b, "\t%s%s\n", strconv.Quote(p), end)
			}
		}
	}

	colls := collArray.FindAllStringSubmatch(s, -1)
	if len(colls) != 1 {
		return nil, fmt.Errorf("%d sCollect arrays", len(colls))
	}
	fmt.Fprintf(&b, "\n// %s are the collections: the name, the levels, the number of levels.\n", goName(colls[0][1]))
	fmt.Fprintf(&b, "var %s = [...]collect{\n", goName(colls[0][1]))
	for _, e := range collEntry.FindAllStringSubmatch(colls[0][2], -1) {
		n, ok := counts[e[2]]
		if !ok {
			return nil, fmt.Errorf("collection %q: no array %s", e[1], e[2])
		}
		fmt.Fprintf(&b, "\t{%s, %s, %d},\n", strconv.Quote(e[1]), goName(e[2]), n)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// item is one string of a level array: its pieces (the C string literals)
// and the comments before it.
type item struct {
	comments []string
	pieces   []string
}

// parseItems splits the body of a C array of strings.
func parseItems(body string) ([]item, error) {
	var items []item
	var cur item
	var comments []string
	for i := 0; i < len(body); {
		switch c := body[i]; {
		case c == '/' && strings.HasPrefix(body[i:], "//"):
			e := strings.IndexByte(body[i:], '\n')
			if e < 0 {
				e = len(body) - i
			}
			comments = append(comments, strings.TrimRight(body[i:i+e], " \t"))
			i += e
		case c == '"':
			var p strings.Builder
			i++
			for ; i < len(body) && body[i] != '"'; i++ {
				if body[i] == '\\' {
					i++
					switch body[i] {
					case '\\', '"', '\'':
						p.WriteByte(body[i])
					default:
						return nil, fmt.Errorf("escape \\%c", body[i])
					}
					continue
				}
				if body[i] == '\n' {
					return nil, fmt.Errorf("a new line in a string")
				}
				p.WriteByte(body[i])
			}
			i++
			if len(cur.pieces) == 0 {
				cur.comments = comments
				comments = nil
			}
			cur.pieces = append(cur.pieces, p.String())
		case c == ',':
			if len(cur.pieces) == 0 {
				return nil, fmt.Errorf("an empty item")
			}
			items = append(items, cur)
			cur = item{}
			i++
		case c == ' ' || c == '\t' || c == '\n':
			i++
		default:
			return nil, fmt.Errorf("unexpected %q", c)
		}
	}
	if len(cur.pieces) > 0 {
		items = append(items, cur)
	}
	return items, nil
}
