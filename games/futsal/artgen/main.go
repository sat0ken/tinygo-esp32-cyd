// Command artgen draws the pictures of package futsal: the pitch seen from
// above (a 4-bit image: 16 colours) and the players (pixel art drawn here,
// four directions of three frames). It writes art.go, the pitch in
// data/pitchImg.dat and previews in art/.
//
//	go generate ./games/futsal   (go run ./artgen in games/futsal)
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"path/filepath"

	"github.com/sat0ken/tinygo-cyd/internal/pixelart"
	"github.com/sat0ken/tinygo-cyd/picopad"
)

// key is the transparent colour of the sprites.
const key = picopad.ColMagenta

// The stand-in colours of the shirts, replaced by each team's colours when
// the game starts.
var (
	teamCol  = picopad.RGB(16, 32, 232)
	teamDark = picopad.RGB(8, 16, 120)
)

// The pitch (the same as in package futsal).
const (
	fieldL, fieldR = 16, 304
	fieldT, fieldB = 38, 232
	midX, midY     = 160, 135
	goalHalf       = 20
	goalDepth      = 10
	areaR          = 40
	hudH           = 30
)

func main() {
	for _, d := range []string{"art", "data"} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			log.Fatal(err)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by artgen. DO NOT EDIT.\n\npackage futsal\n\nimport (\n\t_ \"embed\"\n\n\t\"github.com/sat0ken/tinygo-cyd/picopad\"\n)\n")
	fmt.Fprintf(&b, "\n// The stand-in colours of the shirts in the sprites.\nconst (\n\tstandInTeam = picopad.Color(%#04x)\n\tstandInDark = picopad.Color(%#04x)\n)\n", teamCol, teamDark)

	p := pitch()
	if len(p.Pal) > 16 {
		log.Fatalf("the pitch has %d colours", len(p.Pal))
	}
	pal := p.PalData()
	fmt.Fprintf(&b, "\n// the pitch from above, the score board at the top\n//\n// format: 4-bit paletted pixel graphics\n// image width: 320 pixels\n// image height: 240 lines\n// image pitch: 160 bytes\n")
	fmt.Fprintf(&b, "const pitchImgPal = %s\n\n", pixelart.Literal(pal))
	if err := os.WriteFile(filepath.Join("data", "pitchImg.dat"), pack4(p), 0o644); err != nil {
		log.Fatal(err)
	}
	b.WriteString("//go:embed data/pitchImg.dat\nvar pitchImg string\n")
	if err := p.WritePNG(filepath.Join("art", "pitch.png"), 2); err != nil {
		log.Fatal(err)
	}

	s := players()
	fmt.Fprintf(&b, "\n// a player from above: facing down, up, right, left; standing and two steps each (12 x 12 x 16)\n//\n// format: 8-bit paletted pixel graphics\n// image width: %d pixels\n// image height: %d lines\n// image pitch: %d bytes\n", s.W, s.H, s.W)
	fmt.Fprintf(&b, "const (\n\tplayerW = 12\n\tplayerH = 16\n)\n\n")
	fmt.Fprintf(&b, "const playerImgPal = %s\n\n", pixelart.Literal(s.PalData()))
	fmt.Fprintf(&b, "const playerImg = %s\n", pixelart.Literal(s.Data()))
	if err := s.WritePNG(filepath.Join("art", "player.png"), 4); err != nil {
		log.Fatal(err)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("art.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// pack4 packs the image two pixels a byte (the left one in the high
// nibble), as picopad's 4-bit images.
func pack4(im *pixelart.Image) []byte {
	pitch := (im.W + 1) / 2
	out := make([]byte, pitch*im.H)
	for y := 0; y < im.H; y++ {
		for x := 0; x < im.W; x++ {
			c := im.At(x, y)
			if x&1 == 0 {
				out[y*pitch+x/2] |= c << 4
			} else {
				out[y*pitch+x/2] |= c
			}
		}
	}
	return out
}

// pitch draws the futsal pitch with the boards around it and the goals.
func pitch() *pixelart.Image {
	im := pixelart.New(320, 240, key)
	navy := im.C(16, 22, 48)
	hudLine := im.C(150, 160, 200)
	grassA := im.C(52, 150, 64)
	grassB := im.C(44, 134, 56)
	line := im.C(240, 244, 240)
	board := im.C(40, 70, 130)
	boardL := im.C(70, 110, 180)
	boardD := im.C(20, 34, 70)
	net := im.C(60, 70, 70)
	netL := im.C(170, 180, 180)

	// the boards (everything outside the lines), panels in two blues
	for y := hudH; y < 240; y++ {
		for x := 0; x < 320; x++ {
			c := board
			if (x/40+y/40)%2 == 0 {
				c = boardL
			}
			if y == hudH || y == 239 || x == 0 || x == 319 {
				c = boardD
			}
			im.Set(x, y, c)
		}
	}
	im.Rect(0, 0, 320, hudH, navy)
	im.Rect(0, hudH-1, 320, 1, hudLine)

	// the grass in stripes
	for y := fieldT; y <= fieldB; y++ {
		for x := fieldL; x <= fieldR; x++ {
			c := grassA
			if (x-fieldL)/24%2 == 1 {
				c = grassB
			}
			im.Set(x, y, c)
		}
	}
	// the lines
	frame := func(x0, y0, x1, y1 int) {
		im.Rect(x0, y0, x1-x0+1, 1, line)
		im.Rect(x0, y1, x1-x0+1, 1, line)
		im.Rect(x0, y0, 1, y1-y0+1, line)
		im.Rect(x1, y0, 1, y1-y0+1, line)
	}
	frame(fieldL, fieldT, fieldR, fieldB)
	im.Rect(midX, fieldT, 1, fieldB-fieldT, line)
	ring := func(cx, cy, r float64, inside func(x, y int) bool) {
		for y := fieldT; y <= fieldB; y++ {
			for x := fieldL; x <= fieldR; x++ {
				d := math.Hypot(float64(x)-cx, float64(y)-cy)
				if math.Abs(d-r) < 0.55 && inside(x, y) {
					im.Set(x, y, line)
				}
			}
		}
	}
	all := func(x, y int) bool { return true }
	ring(midX, midY, 22, all)
	im.Rect(midX-1, midY-1, 3, 3, line)
	// the penalty areas: within areaR of the goal mouth
	for _, gx := range []int{fieldL, fieldR} {
		for y := fieldT; y <= fieldB; y++ {
			for x := fieldL; x <= fieldR; x++ {
				dy := math.Max(math.Abs(float64(y-midY))-goalHalf, 0)
				d := math.Hypot(float64(x-gx), dy)
				if math.Abs(d-areaR) < 0.6 {
					im.Set(x, y, line)
				}
			}
		}
		s := 1
		if gx == fieldR {
			s = -1
		}
		im.Rect(gx+s*72-1, midY, 2, 2, line) // the second penalty mark
	}
	// the corners
	for _, c := range [][2]float64{{fieldL, fieldT}, {fieldR, fieldT}, {fieldL, fieldB}, {fieldR, fieldB}} {
		ring(c[0], c[1], 4, all)
	}
	// the goals: the net behind the line, the posts
	for _, gx := range []int{fieldL - goalDepth, fieldR + 1} {
		for y := midY - goalHalf; y <= midY+goalHalf; y++ {
			for x := gx; x < gx+goalDepth; x++ {
				c := net
				if (x+y)%4 == 0 || (x-y+400)%4 == 0 {
					c = netL
				}
				im.Set(x, y, c)
			}
		}
		frame(gx-1, midY-goalHalf-1, gx+goalDepth, midY+goalHalf+1)
	}
	return im
}

// person colours.
type colours struct {
	team, dark, skin, skinD, hair, white, shorts, sock, boot uint8
}

func paints(im *pixelart.Image) colours {
	return colours{
		team: im.Col(teamCol), dark: im.Col(teamDark),
		skin: im.C(246, 196, 150), skinD: im.C(206, 150, 106),
		hair:  im.C(50, 34, 24),
		white: im.C(246, 246, 246), shorts: im.C(230, 232, 240),
		sock: im.Col(teamDark), boot: im.C(24, 24, 30),
	}
}

// player draws a player from above at an angle: dir 0 facing down (to us),
// 1 up, 2 right; step 0 standing, 1 and 2 the strides.
func player(dir, step int) *pixelart.Image {
	im := pixelart.New(12, 16, key)
	c := paints(im)
	// the legs
	l, r := 0, 0
	switch step {
	case 1:
		l, r = -1, 1
	case 2:
		l, r = 1, -1
	}
	if dir == 2 { // from the side: the legs apart
		im.Rect(4+2*l, 12, 2, 3, c.skin)
		im.Rect(6+2*r, 12, 2, 3, c.skin)
		im.Rect(4+2*l, 13, 2, 1, c.sock)
		im.Rect(6+2*r, 13, 2, 1, c.sock)
		im.Rect(4+2*l, 15, 3, 1, c.boot)
		im.Rect(6+2*r, 15, 3, 1, c.boot)
	} else {
		im.Rect(3, 12+l, 2, 3, c.skin)
		im.Rect(7, 12+r, 2, 3, c.skin)
		im.Rect(3, 13+l, 2, 1, c.sock)
		im.Rect(7, 13+r, 2, 1, c.sock)
		im.Rect(3, 14+l, 2, 2, c.boot)
		im.Rect(7, 14+r, 2, 2, c.boot)
	}
	// the shorts and the shirt
	if dir == 2 {
		im.Rect(4, 10, 5, 3, c.shorts)
		im.Rect(3, 5, 6, 6, c.team)
		im.Rect(3, 5, 1, 6, c.dark)
		im.Rect(5, 6, 2, 4, c.skin) // the arm
		im.Rect(5+r, 9, 2, 1, c.skinD)
	} else {
		im.Rect(3, 10, 6, 3, c.shorts)
		im.Rect(2, 5, 8, 6, c.team)
		im.Rect(2, 5, 8, 1, c.dark)
		im.Rect(1, 6, 1, 4, c.skin) // the arms
		im.Rect(10, 6, 1, 4, c.skin)
		if dir == 1 {
			im.Rect(5, 6, 2, 3, c.dark) // the number on the back
		}
	}
	// the head
	switch dir {
	case 0:
		im.Ellipse(6, 3, 2.8, 2.8, c.skin)
		im.Rect(4, 0, 5, 2, c.hair)
		im.Set(5, 3, c.boot)
		im.Set(7, 3, c.boot)
	case 1:
		im.Ellipse(6, 3, 2.8, 2.8, c.hair)
	case 2:
		im.Ellipse(6, 3, 2.8, 2.8, c.skin)
		im.Rect(4, 0, 5, 2, c.hair)
		im.Rect(4, 2, 2, 2, c.hair)
		im.Set(8, 3, c.boot)
	}
	im.Outline(im.C(20, 24, 30))
	return im
}

func players() *pixelart.Image {
	var frames []*pixelart.Image
	for dir := 0; dir < 3; dir++ {
		for s := 0; s < 3; s++ {
			frames = append(frames, player(dir, s))
		}
	}
	for s := 0; s < 3; s++ { // facing left: the right ones mirrored
		f := player(2, s)
		f.FlipX()
		frames = append(frames, f)
	}
	return pixelart.Join(frames...)
}
