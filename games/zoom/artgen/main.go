// digits are 7-segment digits, yellow to orange, with a dark outline.
func digits() *pixelart.Image {
	segs := map[byte][4]int{ // x, y, w, h
		'a': {3, 1, 10, 3}, 'b': {12, 2, 3, 8}, 'c': {12, 10, 3, 8}, 'd': {3, 16, 10, 3},
		'e': {1, 10, 3, 8}, 'f': {1, 2, 3, 8}, 'g': {3, 8, 10, 3},
	}
	on := []string{"abcdef", "bc", "abged", "abgcd", "fgbc", "afgcd", "afgedc", "abc", "abcdefg", "abcdfg"}
	var frames []*pixelart.Image
	for _, d := range on {
		im := pixelart.New(16, 20, key)
		grad := ramp(im, 18, rgb{255, 245, 110}, rgb{255, 140, 30})
		for i := 0; i < len(d); i++ {
			s := segs[d[i]]
			for y := s[1]; y < s[1]+s[3]; y++ {
				for x := s[0]; x < s[0]+s[2]; x++ {
					im.Set(x, y, grad[y-1])
				}
			}
		}
		im.Outline(im.C(25, 20, 50))
		frames = append(frames, im)
	}
	return pixelart.Join(frames...)
}

// city draws domes and towers on the horizon (more of them for n 2).
func city(w, h, n int) *pixelart.Image {
	im := pixelart.New(w, h, key)
	glass := ramp(im, 3, rgb{40, 120, 140}, rgb{90, 200, 205}, rgb{220, 255, 250})
	tower := im.C(120, 70, 185)
	light := im.C(255, 90, 200)
	type dome struct{ x, r float64 }
	type spire struct{ x, h int }
	domes := []dome{{14, 6}, {24, 7.5}, {35, 5}}
	spires := []spire{{8, 6}, {19, 7}, {30, 6}, {40, 5}}
	if n == 2 {
		domes = []dome{{12, 5}, {24, 7}, {41, 8.5}, {57, 6.5}, {71, 5}}
		spires = []spire{{6, 6}, {18, 7}, {32, 8}, {50, 8}, {64, 6}, {77, 5}}
	}
	for _, s := range spires {
		im.Rect(s.x, h-s.h, 2, s.h, tower)
		im.Set(s.x, h-s.h, light)
	}
	for _, d := range domes {
		im.Ball(d.x, float64(h), d.r, glass)
	}
	return im
}

// skyline is the sky (a gradient) with two ranges of mountains and snow on
// the high peaks of the far one.
func skyline() *pixelart.Image {
	const w, h = 320, 56
	im := pixelart.New(w, h, key)
	rnd := rand.New(rand.NewSource(3))
	// a ridge from top to bottom (Y of the highest and lowest peaks):
	// midpoint displacement that wraps around
	ridge := func(top, bottom float64) []float64 {
		n := 512
		v := make([]float64, n)
		for step := n / 2; step >= 1; step /= 2 {
			for i := 0; i < n; i += 2 * step {
				a, b := v[i], v[(i+2*step)%n]
				v[i+step] = (a+b)/2 + (rnd.Float64()-0.5)*float64(step)
			}
		}
		lo, hi := v[0], v[0]
		for _, e := range v {
			lo, hi = math.Min(lo, e), math.Max(hi, e)
		}
		out := make([]float64, w)
		for x := range out {
			out[x] = bottom - (v[x*n/w]-lo)/(hi-lo)*(bottom-top)
		}
		return out
	}
	far := ridge(28, 50)
	near := ridge(44, 54)
	sky := []rgb{{6, 8, 36}, {28, 40, 110}, {90, 120, 200}, {200, 190, 220}}
	for y := 0; y < h; y++ {
		t := float64(y) / float64(h-1) * 3
		k := min(int(t), 2)
		// bands of 2 lines: fewer colours
		c := sky[k].lerp(sky[k+1], math.Floor((t-float64(k))*12)/12).in(im)
		for x := 0; x < w; x++ {
			im.Set(x, y, c)
		}
	}
	rock := ramp(im, 3, rgb{70, 70, 120}, rgb{110, 105, 160}, rgb{150, 140, 190})
	snow := im.C(230, 235, 250)
	nearCol := ramp(im, 2, rgb{38, 40, 75}, rgb{60, 60, 100})
	for x := 0; x < w; x++ {
		top := int(math.Round(far[x]))
		for y := max(top, 0); y < h; y++ {
			c := rock[min((y-top)/3, 2)]
			if y < 40 && y-top < 3 {
				c = snow
			}
			im.Set(x, y, c)
		}
		top = int(math.Round(near[x]))
		for y := max(top, 0); y < h; y++ {
			im.Set(x, y, nearCol[min((y-top)/2, 1)])
		}
	}
	return im
}

// title draws GATE RUNNER in the bold 8x8 font of picopad four times as
// large, slanted, chrome above the middle and sunset below, with a dark
// outline.
func title() *pixelart.Image {
	const w, h = 230, 72
	im := pixelart.New(w, h, key)
	d := memlcd.New(320, 240)
	c := picopad.New(d, nil, 0)
	c.SelFont8x8()
	lines := []string{"GATE", "RUNNER"}
	for i, l := range lines {
		c.DrawText(l, 0, i*8, picopad.ColWhite)
	}
	c.DispUpdate()
	glyphs := d.Image()
	upper := ramp(im, 14, rgb{120, 200, 255}, rgb{255, 255, 255})
	lower := ramp(im, 14, rgb{255, 190, 70}, rgb{210, 40, 130})
	for i, l := range lines {
		lw := len(l) * 8 * 4
		x0 := (w - lw - 7) / 2
		y0 := 2 + i*36
		for y := 0; y < 32; y++ {
			col := upper[min(y, 13)]
			if y >= 16 {
				col = lower[min(y-16, 13)]
			}
			slant := (31 - y) / 4
			for x := 0; x < lw; x++ {
				r, _, _, _ := glyphs.At(x/4, i*8+y/4).RGBA()
				if r != 0 {
					im.Set(x0+x+slant, y0+y, col)
				}
			}
		}
	}
	im.Outline(im.C(30, 15, 70))
	im.Outline(im.C(12, 6, 30))
	return im
}
