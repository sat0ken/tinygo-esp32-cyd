// Command artgen draws the pictures of package zoom (Gate Runner). The C
// game is a version of a 1984 arcade game and has that game's title and
// pictures, so all of them (but the grass, which is gradients) are drawn
// here anew, at the sizes of the C pictures: art.go, the larger ones in
// data/*.dat, and previews in art/.
//
//	go generate ./games/zoom   (go run ./artgen in games/zoom)
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"math/rand"
	"os"
	"path/filepath"

	"github.com/sat0ken/tinygo-cyd/internal/pixelart"
	"github.com/sat0ken/tinygo-cyd/memlcd"
	"github.com/sat0ken/tinygo-cyd/picopad"
)

// key is the transparent colour of all the pictures.
const key = picopad.ColMagenta

func main() {
	for _, d := range []string{"art", "data"} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			log.Fatal(err)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by artgen. DO NOT EDIT.\n\npackage zoom\n\nimport _ \"embed\"\n")

	pics := []struct {
		name, about string
		w, h        int // a frame
		img         *pixelart.Image
	}{
		{"title", "the title: GATE RUNNER", 230, 72, title()},
		{"skyline", "the sky and the mountains above the horizon", 320, 56, skyline()},
		{"city1", "the city on the horizon in sector 2", 48, 7, city(48, 7, 1)},
		{"city2", "the city from sector 3", 82, 8, city(82, 8, 2)},
		{"ship", "the ship: up, banking left and right, its shadow (4 x 56 x 15, one under the other)", 56, 15, ship()},
		{"live", "a life (a small ship)", 22, 6, live()},
		{"ufo", "a saucer in 8 sizes (40 x 16, one under the other)", 40, 16, sizes(40, 16, false, true, ufo)},
		{"walker", "a walker in 8 sizes (31 x 46, side by side)", 31, 46, sizes(31, 46, true, true, walker)},
		{"boss", "the mother ship in 8 sizes (76 x 29, one under the other)", 76, 29, sizes(76, 29, false, false, boss)},
		{"gate", "a pylon of a gate in 8 sizes (24 x 40, side by side)", 24, 40, sizes(24, 40, true, true, pylon)},
		{"bomb", "a bomb in 8 sizes (14 x 9, one under the other)", 14, 9, sizes(14, 9, false, false, bomb)},
		{"shot", "a shot in 4 sizes (13 x 4, one under the other)", 13, 4, shots()},
		{"explosion", "an explosion in 8 phases (104 x 48, one under the other), smaller and darker", 104, 48, explosion()},
		{"digit", "the digits 0 to 9 of the score (16 x 20, side by side)", 16, 20, digits()},
		{"goal", "a goal left", 12, 8, goal()},
	}
	for _, p := range pics {
		im := p.img
		fmt.Fprintf(&b, "\n// %s\n//\n// format: 8-bit paletted pixel graphics\n// image width: %d pixels\n// image height: %d lines\n// image pitch: %d bytes\n",
			p.about, im.W, im.H, im.W)
		fmt.Fprintf(&b, "const (\n\t%sW = %d\n\t%sH = %d\n)\n\n", p.name, p.w, p.name, p.h)
		fmt.Fprintf(&b, "const %sImgPal = %s\n\n", p.name, pixelart.Literal(im.PalData()))
		if len(im.Pix) >= 1024 {
			file := p.name + "Img.dat"
			if err := os.WriteFile(filepath.Join("data", file), im.Data(), 0o644); err != nil {
				log.Fatal(err)
			}
			fmt.Fprintf(&b, "//go:embed data/%s\nvar %sImg string\n", file, p.name)
		} else {
			fmt.Fprintf(&b, "const %sImg = %s\n", p.name, pixelart.Literal(im.Data()))
		}
		scale := 3
		if im.W*im.H > 20000 {
			scale = 2
		}
		if err := im.WritePNG(filepath.Join("art", p.name+".png"), scale); err != nil {
			log.Fatal(err)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("art.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// rgb is a colour of 8-bit components.
type rgb struct{ r, g, b float64 }

func (c rgb) lerp(d rgb, t float64) rgb {
	return rgb{c.r + (d.r-c.r)*t, c.g + (d.g-c.g)*t, c.b + (d.b-c.b)*t}
}

func (c rgb) in(im *pixelart.Image) uint8 {
	cl := func(v float64) uint8 { return uint8(math.Max(0, math.Min(255, math.Round(v)))) }
	return im.C(cl(c.r), cl(c.g), cl(c.b))
}

// ramp adds the colours from a to b in n steps.
func ramp(im *pixelart.Image, n int, cols ...rgb) []uint8 {
	var out []uint8
	for i := 0; i < n; i++ {
		t := float64(i) / float64(n-1) * float64(len(cols)-1)
		k := min(int(t), len(cols)-2)
		out = append(out, cols[k].lerp(cols[k+1], t-float64(k)).in(im))
	}
	return out
}

// xf maps the coordinates of a design to a frame: X = ox + x*s, Y = oy +
// y*s.
type xf struct{ ox, oy, s float64 }

func (t xf) X(x float64) float64 { return t.ox + x*t.s }
func (t xf) Y(y float64) float64 { return t.oy + y*t.s }

// r is a radius at least half a pixel.
func (t xf) r(r float64) float64 { return math.Max(r*t.s, 0.6) }

func (t xf) ellipse(im *pixelart.Image, cx, cy, rx, ry float64, c uint8) {
	im.Ellipse(t.X(cx), t.Y(cy), t.r(rx), t.r(ry), c)
}

func (t xf) ball(im *pixelart.Image, cx, cy, r float64, ramp []uint8) {
	im.Ball(t.X(cx), t.Y(cy), t.r(r), ramp)
}

func (t xf) poly(im *pixelart.Image, c uint8, pts ...float64) {
	q := make([]float64, len(pts))
	for i := 0; i < len(pts); i += 2 {
		q[i], q[i+1] = t.X(pts[i]), t.Y(pts[i+1])
	}
	im.Poly(c, q...)
}

func (t xf) line(im *pixelart.Image, x0, y0, x1, y1 float64, c uint8) {
	im.Line(int(math.Floor(t.X(x0))), int(math.Floor(t.Y(y0))), int(math.Floor(t.X(x1))), int(math.Floor(t.Y(y1))), c)
}

func (t xf) dot(im *pixelart.Image, x, y float64, c uint8) {
	im.Set(int(math.Floor(t.X(x))), int(math.Floor(t.Y(y))), c)
}

// sizes draws 8 sizes of a design (1, 7/8 ... 1/8) side by side (horiz)
// or one under the other, each w x h. The design's origin is the bottom
// middle of the frame (bottom) or its middle.
func sizes(w, h int, horiz, bottom bool, design func(im *pixelart.Image, t xf)) *pixelart.Image {
	var frames []*pixelart.Image
	for k := 0; k < 8; k++ {
		f := pixelart.New(w, h, key)
		s := 1 - float64(k)/8
		t := xf{float64(w) / 2, float64(h) / 2, s}
		if bottom {
			t.oy = float64(h)
		}
		design(f, t)
		frames = append(frames, f)
	}
	if horiz {
		return pixelart.Join(frames...)
	}
	return stack(frames...)
}

// stack puts frames of the same size one under the other with one palette.
func stack(frames ...*pixelart.Image) *pixelart.Image {
	w, h := frames[0].W, frames[0].H
	out := pixelart.New(w, h*len(frames), key)
	for k, f := range frames {
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				if c := f.At(x, y); c != 0 {
					out.Set(x, k*h+y, out.Col(f.Pal[c]))
				}
			}
		}
	}
	return out
}

// ufo is a red saucer with a glass dome and lights, and its shadow (40 x
// 16, bottom middle).
func ufo(im *pixelart.Image, t xf) {
	shadow := im.C(24, 36, 24)
	under := im.C(110, 28, 36)
	body := im.C(205, 55, 50)
	top := im.C(255, 135, 95)
	light := im.C(255, 230, 90)
	glass := ramp(im, 4, rgb{20, 90, 140}, rgb{90, 200, 240}, rgb{230, 250, 255})
	t.ellipse(im, 0, -1.5, 12, 1.5, shadow)
	t.ellipse(im, 0, -7.5, 19.5, 3.6, body)
	t.ellipse(im, 0, -5.8, 13, 1.6, under)
	t.ellipse(im, 0, -8.6, 15, 1.8, top)
	t.ball(im, 0, -10.5, 5.5, glass)
	t.ellipse(im, 0, -8.6, 6, 0.9, body) // the rim of the dome
	if t.s >= 0.5 {
		for _, x := range []float64{-13, -6.5, 0, 6.5, 13} {
			t.dot(im, x, -7.2, light)
		}
	}
}

// walker is a three-legged walker with a round body and an eye (31 x 46,
// bottom middle).
func walker(im *pixelart.Image, t xf) {
	shadow := im.C(24, 36, 24)
	leg := im.C(120, 120, 140)
	legDark := im.C(70, 70, 90)
	body := ramp(im, 5, rgb{20, 70, 80}, rgb{40, 150, 150}, rgb{170, 240, 230})
	eye := im.C(230, 40, 60)
	pupil := im.C(255, 230, 60)
	t.ellipse(im, 0, -1.2, 13, 1.4, shadow)
	// the legs (two lines each when large)
	for _, l := range [][4]float64{{-5, -32, -13, -1}, {5, -32, 13, -1}, {0, -30, 0, -1}} {
		c := leg
		if l[0] == 0 {
			c = legDark
		}
		t.line(im, l[0], l[1], l[2], l[3], c)
		if t.s > 0.55 {
			t.line(im, l[0]+1/t.s, l[1], l[2]+1/t.s, l[3], c)
		}
		t.ellipse(im, l[2]+0.5, -1.2, 2.2, 1, legDark) // a foot
	}
	t.ellipse(im, 0, -30, 6, 3, legDark) // the joint under the body
	t.ball(im, 0, -36, 9.5, body)
	t.ellipse(im, 0, -35, 5, 2.2, eye)
	t.ellipse(im, 0, -35, 2, 1.2, pupil)
}

// boss is the mother ship: a wide hull, a deck with a dome, side pods,
// windows and a glow under it (76 x 29, middle).
func boss(im *pixelart.Image, t xf) {
	hull := im.C(60, 70, 115)
	hullLight := im.C(105, 118, 170)
	pod := im.C(45, 50, 85)
	glow := ramp(im, 3, rgb{255, 120, 30}, rgb{255, 220, 80})
	window := im.C(255, 230, 120)
	dome := ramp(im, 4, rgb{120, 20, 30}, rgb{230, 60, 50}, rgb{255, 190, 160})
	antenna := im.C(150, 150, 170)
	tip := im.C(255, 60, 60)
	t.ellipse(im, 0, 6, 16, 3, glow[0])
	t.ellipse(im, 0, 6, 9, 1.8, glow[2])
	t.ellipse(im, -28, 2.5, 9, 4.2, pod)
	t.ellipse(im, 28, 2.5, 9, 4.2, pod)
	t.ellipse(im, -33, 3, 2.5, 2, glow[1])
	t.ellipse(im, 33, 3, 2.5, 2, glow[1])
	t.ellipse(im, 0, 1, 37.5, 7, hull)
	t.ellipse(im, 0, -3, 23, 5.5, hullLight)
	if t.s >= 0.4 {
		for x := -24.0; x <= 24; x += 6 {
			t.dot(im, x, 2.5, window)
		}
		t.line(im, -7, -9, -11, -14, antenna)
		t.line(im, 7, -9, 11, -14, antenna)
		t.dot(im, -11, -14, tip)
		t.dot(im, 11, -14, tip)
	}
	t.ball(im, 0, -7, 6.5, dome)
}

// pylon is a striped post with a glowing ball on a base (24 x 40, bottom
// middle).
func pylon(im *pixelart.Image, t xf) {
	base := im.C(60, 60, 75)
	post := im.C(85, 85, 100)
	edge := im.C(165, 165, 180)
	stripe := im.C(250, 200, 40)
	orb := ramp(im, 4, rgb{0, 80, 150}, rgb{40, 170, 230}, rgb{150, 235, 255}, rgb{255, 255, 255})
	t.poly(im, base, -8, 0, 8, 0, 5, -6, -5, -6)
	t.poly(im, post, -3, -5, 3, -5, 3, -32, -3, -32)
	t.poly(im, edge, -3, -5, -1.5, -5, -1.5, -32, -3, -32)
	if t.s >= 0.3 {
		for y := -28.0; y < -6; y += 8 {
			t.poly(im, stripe, -3, y+3, 3, y+3, 3, y, -3, y)
		}
	}
	t.ball(im, 0, -34, 6, orb)
}

// bomb is a glowing ball (14 x 9, middle).
func bomb(im *pixelart.Image, t xf) {
	glow := ramp(im, 5, rgb{150, 0, 60}, rgb{255, 40, 120}, rgb{255, 150, 200}, rgb{255, 255, 255})
	t.ellipse(im, 0, 0, 7, 4.5, glow[0])
	t.ball(im, 0, 0, 4, glow[1:])
}

// shots are a cyan bolt in 4 sizes.
func shots() *pixelart.Image {
	var frames []*pixelart.Image
	for _, s := range []float64{1, 0.7, 0.42, 0.25} {
		f := pixelart.New(13, 4, key)
		t := xf{6.5, 2, s}
		t.ellipse(f, 0, 0, 6.5, 2, f.C(40, 160, 255))
		t.ellipse(f, 0, 0, 4.5, 1, f.C(220, 250, 255))
		frames = append(frames, f)
	}
	return stack(frames...)
}

// explosion draws 8 phases of a burst of fire, each smaller and cooler
// (the C game starts an explosion at the phase of the size of the enemy).
func explosion() *pixelart.Image {
	rnd := rand.New(rand.NewSource(7))
	sizes := []float64{1, 0.8, 0.6, 0.43, 0.3, 0.22, 0.17, 0.13}
	// the rays of the burst (the same in every phase)
	type ray struct{ a, l float64 }
	var rays []ray
	for i := 0; i < 26; i++ {
		rays = append(rays, ray{rnd.Float64() * 2 * math.Pi, 0.55 + 0.45*rnd.Float64()})
	}
	noise := make([]float64, 104*48)
	for i := range noise {
		noise[i] = rnd.Float64()
	}
	var frames []*pixelart.Image
	for k, s := range sizes {
		f := pixelart.New(104, 48, key)
		hot := []rgb{{255, 255, 255}, {255, 245, 160}, {255, 200, 40}, {255, 120, 20}, {220, 40, 20}, {120, 20, 30}}
		cool := []rgb{{255, 220, 120}, {255, 160, 40}, {230, 80, 20}, {160, 40, 30}, {90, 40, 50}, {60, 50, 60}}
		c := float64(k) / 7
		var cols []uint8
		for i := range hot {
			cols = append(cols, hot[i].lerp(cool[i], c).in(f))
		}
		rx, ry := 51*s, 23*s
		for y := 0; y < 48; y++ {
			for x := 0; x < 104; x++ {
				dx, dy := (float64(x)+0.5-52)/rx, (float64(y)+0.5-24)/ry
				d := math.Hypot(dx, dy)
				a := math.Atan2(dy, dx)
				// the rays reach further
				reach := 0.6
				for _, r := range rays {
					da := math.Abs(math.Remainder(a-r.a, 2*math.Pi))
					if da < 0.12 {
						reach = math.Max(reach, r.l*(1-da/0.12*0.5))
					}
				}
				v := d/reach + 0.35*(noise[y*104+x]-0.5)
				if v >= 1 {
					continue
				}
				f.Set(x, y, cols[min(int(v*float64(len(cols))), len(cols)-1)])
			}
		}
		frames = append(frames, f)
	}
	return stack(frames...)
}

// ship is the player's ship from behind: wide wings with red tips, a body
// with a blue canopy, two fins and two engines; banked to the left and to
// the right; and its shadow.
func ship() *pixelart.Image {
	draw := func(roll float64) *pixelart.Image {
		im := pixelart.New(56, 15, key)
		wing := im.C(215, 220, 230)
		wingDark := im.C(130, 135, 150)
		red := im.C(230, 40, 40)
		body := ramp(im, 3, rgb{110, 115, 130}, rgb{190, 195, 210}, rgb{250, 250, 255})
		canopy := ramp(im, 3, rgb{20, 50, 140}, rgb{60, 140, 240}, rgb{200, 240, 255})
		flame := im.C(255, 170, 40)
		core := im.C(255, 250, 180)
		// roll: y moves with x (shear around the middle)
		sh := func(pts ...float64) []float64 {
			for i := 0; i < len(pts); i += 2 {
				pts[i+1] += (pts[i] - 28) * roll
			}
			return pts
		}
		im.Poly(wingDark, sh(1, 10, 25, 7, 31, 7, 55, 10, 55, 12, 31, 10.5, 25, 10.5, 1, 12)...)
		im.Poly(wing, sh(1, 9, 25, 5, 31, 5, 55, 9, 55, 10.5, 31, 8, 25, 8, 1, 10.5)...)
		im.Poly(red, sh(0, 8, 3, 8, 3, 12, 0, 12)...)
		im.Poly(red, sh(53, 8, 56, 8, 56, 12, 53, 12)...)
		im.Poly(red, sh(21, 1, 23, 1, 24, 7, 21, 7)...)
		im.Poly(red, sh(33, 1, 35, 1, 35, 7, 32, 7)...)
		c := sh(28, 7.5)
		im.Ball(c[0], c[1], 5.6, body)
		c = sh(28, 5.6)
		im.Ball(c[0], c[1], 2.8, canopy)
		for _, x := range []float64{24.5, 31.5} {
			e := sh(x, 11.5)
			im.Ellipse(e[0], e[1], 2.2, 1.6, flame)
			im.Ellipse(e[0], e[1], 1, 0.8, core)
		}
		return im
	}
	up, left, right := draw(0), draw(0.11), draw(-0.11)
	shadow := pixelart.New(56, 15, key)
	dark := shadow.C(16, 28, 16)
	shadow.Poly(dark, 1, 8.5, 25, 6.5, 31, 6.5, 55, 8.5, 55, 9.8, 31, 10.5, 25, 10.5, 1, 9.8)
	shadow.Ellipse(28, 8.5, 6, 2.2, dark)
	return stack(up, left, right, shadow)
}

// live is a small ship.
func live() *pixelart.Image {
	im := pixelart.New(22, 6, key)
	k := map[byte]uint8{'w': im.C(215, 220, 230), 'r': im.C(230, 40, 40), 'b': im.C(60, 140, 240), 'o': im.C(255, 170, 40)}
	im.Stamp(0, 0, k,
		"........r..r..........",
		"........rwwr..........",
		"r.....wwwbbwww......r.",
		"rwwwwwwwwwwwwwwwwwwwwr",
		"r.......owwo........r.",
		"........o..o..........",
	)
	// symmetric: the stamp above is drawn for the left half
	for y := 0; y < 6; y++ {
		for x := 0; x < 11; x++ {
			im.Set(21-x, y, im.At(x, y))
		}
	}
	return im
}

