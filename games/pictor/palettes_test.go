// fixedColors are the colours of the header, the foot and the texts, and
// the 16 greys of the start of a scene (dispShadow), exact in each
// palette.
func fixedColors() []picopad.Color {
	cols := []picopad.Color{picopad.ColWhite, picopad.ColYellow, picopad.ColGreen, picopad.ColRed, picopad.ColCyan,
		picopad.ColMagenta, colAzure, headerCol, headerFrame}
	for k := picopad.Color(0); k < 16; k++ {
		cols = append(cols, k|k<<6|k<<11)
	}
	return cols
}

// sceneImages are the pictures of scene s and how much their colours
// count: the background, the enemies, the new helper and Bara more, the
// helpers before, the missiles, bullets, explosions and bonuses.
func sceneImages(s int) []palquant.Image {
	img8 := func(img string, pal picopad.Palette, w int, trans picopad.Color) palquant.Image {
		return palquant.Image{Img: img, Pal: string(pal), Bits: 8, Weight: w, Trans: trans, HasTrans: true}
	}
	img4 := func(img string, pal picopad.Palette, w int) palquant.Image {
		return palquant.Image{Img: img, Pal: string(pal), Bits: 4, Weight: w, Trans: picopad.ColMagenta, HasTrans: true}
	}
	b := &backTemps[s]
	imgs := []palquant.Image{
		{Img: b.img1, Pal: string(b.pal1), Bits: 8, Weight: 2},
		img8(b.img2, b.pal2, 1, picopad.ColWhite),
		img8(b.img3, b.pal3, 1, picopad.ColWhite),
	}
	for j := 0; j < enemyLevNum; j++ {
		e := &enemyTemps[s*enemyLevNum+j]
		imgs = append(imgs, img8(e.img, e.pal, 3, picopad.ColMagenta))
	}
	for a := 0; a <= s+1; a++ {
		w := 1
		switch a {
		case s + 1:
			w = 3
		case actJill:
			w = 2
		}
		imgs = append(imgs, img8(actorTemps[a].img, actorTemps[a].pal, w, actorTemps[a].trans))
		imgs = append(imgs, img4(missileTemps[a].img, missileTemps[a].pal, 2))
	}
	for _, t := range bulletTemps {
		imgs = append(imgs, img4(t.img, t.pal, 2))
	}
	imgs = append(imgs, img4(explosionImg, explosionImgPal, 2), img4(bloodImg, bloodImgPal, 1),
		img4(bonuscloudImg, bonuscloudImgPal, 2))
	for _, t := range bonusTemps {
		imgs = append(imgs, img4(t.img, t.pal, 1))
	}
	return imgs
}

// TestPalettes makes the palettes of the scenes and compares them with
// palettes.go (-update rewrites it).
func TestPalettes(t *testing.T) {
	var b bytes.Buffer
	b.WriteString("// Code generated by TestPalettes (go test -run TestPalettes -update). DO NOT EDIT.\n\n")
	b.WriteString("package pictor\n\nimport \"github.com/sat0ken/tinygo-cyd/picopad\"\n\n")
	b.WriteString("// scenePal are the palettes of the scenes: the colours of the header and\n// the texts, 16 greys, and the colours of the pictures of the scene\n// (median cut, internal/palquant).\n")
	b.WriteString("var scenePal = [bgNum]picopad.Palette{\n")
	same := true
	for s := 0; s < bgNum; s++ {
		pal := palquant.Palette(fixedColors(), sceneImages(s))
		if len(pal) != 512 {
			t.Errorf("scene %d: %d colours", s, len(pal)/2)
		}
		if s >= len(scenePal) || string(scenePal[s]) != pal {
			same = false
		}
		fmt.Fprintf(&b, "\t// %s\n\t%s,\n", backTemps[s].name, pixelart.Literal([]byte(pal)))
	}
	b.WriteString("}\n")
	if same {
		return
	}
	if !goldentest.Updating() {
		t.Fatal("palettes.go is out of date: go test -run TestPalettes -update")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("palettes.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Log("palettes.go rewritten")
}
