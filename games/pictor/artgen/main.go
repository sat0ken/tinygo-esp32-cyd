// Command artgen draws the pictures of package pictor that replace the
// ones of the C source that cannot be distributed (characters of films:
// R2-D2, the starship Enterprise, a Klingon warship, the Death Star,
// Ant-Man; and the logo of a shop on the title), and writes art.go, the
// title in data/titleImg.dat and previews in art/.
//
//	PICOLIBSDK=~/PicoLibSDK go generate ./games/pictor
//
// (go run ./artgen -root $PICOLIBSDK in games/pictor: the title is the
// one of the C source with the logo cleared.)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/sat0ken/tinygo-cyd/internal/pixelart"
	"github.com/sat0ken/tinygo-cyd/picopad"
)

// magenta is the transparent colour of the sprites (COL_MAGENTA).
const magenta = picopad.ColMagenta

func main() {
	root := flag.String("root", "", "the PicoLibSDK directory (for the title)")
	flag.Parse()
	if *root == "" {
		log.Fatal("usage: artgen -root ~/PicoLibSDK")
	}
	if err := os.MkdirAll("art", 0o755); err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by artgen. DO NOT EDIT.\n\npackage pictor\n\nimport _ \"embed\"\n")

	sprites := []struct {
		name, about string
		img         *pixelart.Image
	}{
		{"robot", "08 Robot: the helper of the spacecraft (4 phases of 50 x 61, walking)", robot()},
		{"cruiser", "09 Star Cruiser (60 x 17)", cruiser()},
		{"warship", "09 Warship (50 x 26)", warship()},
		{"mine", "09 Space Mine (40 x 40)", mine()},
		{"fireant", "03 Fire Ant (2 phases of 50 x 46)", fireAnt()},
	}
	for _, s := range sprites {
		s.img.WriteGo(&b, s.name, s.about)
		if err := s.img.WritePNG(filepath.Join("art", s.name+".png"), 3); err != nil {
			log.Fatal(err)
		}
	}

	// the title without the logo of the shop
	pal, img := title(*root)
	if err := os.WriteFile(filepath.Join("data", "titleImg.dat"), img, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Fprintf(&b, "\n// the title of the C source (img/title.cpp, decompressed) without the logo\n// of the shop in the upper left corner\n//\n// format: 8-bit paletted pixel graphics\n// image width: 320 pixels\n// image height: 240 lines\n// image pitch: 320 bytes\n")
	fmt.Fprintf(&b, "const titleImgPal = %s\n\n//go:embed data/titleImg.dat\nvar titleImg string\n", pixelart.Literal(pal))
	t := &pixelart.Image{W: 320, H: 240, Pix: img}
	for i := 0; i < len(pal)/2; i++ {
		t.Pal = append(t.Pal, picopad.Color(pal[2*i])|picopad.Color(pal[2*i+1])<<8)
	}
	if err := t.WritePNG(filepath.Join("art", "title.png"), 1); err != nil {
		log.Fatal(err)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("art.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// ramp returns the indices of n shades of r, g, b, dark to light.
func ramp(im *pixelart.Image, r, g, b uint8, n int) []uint8 {
	out := make([]uint8, n)
	base := im.C(r, g, b)
	for i := range out {
		out[i] = im.Shade(base, 0.45+1.0*float64(i)/float64(n-1))
	}
	return out
}

// robot is a small robot on caterpillar tracks with a box head, one wide
// eye and two antennas (facing right), its tracks and lights moving.
func robot() *pixelart.Image {
	var frames []*pixelart.Image
	for ph := 0; ph < 4; ph++ {
		im := pixelart.New(50, 61, magenta)
		ink := im.C(20, 24, 40)
		steel := ramp(im, 120, 140, 170, 5)
		blue := ramp(im, 40, 90, 200, 4)
		dark := im.C(45, 50, 65)
		red := im.C(255, 40, 30)
		glow := im.C(255, 210, 60)

		// tracks
		im.Rect(6, 49, 38, 10, dark)
		im.Ellipse(9, 54, 5, 5, dark)
		im.Ellipse(41, 54, 5, 5, dark)
		for x := 6 + (ph*3)%6; x < 44; x += 6 { // the treads moving
			im.Rect(x, 49, 2, 2, steel[1])
			im.Rect(x, 57, 2, 2, steel[1])
		}
		for _, wx := range []float64{12, 21, 30, 39} {
			im.Ball(wx, 54, 3, steel[1:])
		}

		// body
		im.Rect(10, 30, 30, 18, steel[2])
		im.Rect(10, 30, 30, 3, steel[3])
		im.Rect(10, 45, 30, 3, steel[1])
		im.Rect(14, 34, 22, 9, blue[1])
		im.Rect(15, 35, 20, 7, blue[2])
		for i := 0; i < 3; i++ { // the lights of the panel
			c := steel[0]
			if (ph+i)%3 == 0 {
				c = glow
			}
			im.Rect(17+i*6, 37, 4, 3, c)
		}

		// neck and head
		im.Rect(22, 25, 6, 5, steel[1])
		im.Rect(12, 9, 28, 17, steel[2])
		im.Rect(12, 9, 28, 3, steel[3])
		im.Rect(12, 23, 28, 3, steel[1])
		im.Rect(16, 14, 22, 6, ink)     // the visor
		im.Rect(30-ph%2, 15, 6, 4, red) // the eye looking about
		im.Rect(31-ph%2, 15, 2, 1, im.C(255, 200, 190))

		// antennas
		im.Line(16, 9, 14, 2, steel[1])
		im.Line(34, 9, 37, 3, steel[1])
		tip := red
		if ph >= 2 {
			tip = glow
		}
		im.Ball(14, 2, 2, []uint8{tip})
		im.Ball(37, 3, 1.6, []uint8{blue[3]})

		// arm (swinging) with a claw
		ay := 36 + []int{0, 1, 2, 1}[ph]
		im.Rect(40, 33, 4, 4, steel[1])
		im.Line(43, 35, 47, ay, steel[1])
		im.Line(44, 35, 48, ay, steel[2])
		im.Rect(46, ay, 3, 2, dark)

		im.Outline(ink)
		frames = append(frames, im)
	}
	return pixelart.Join(frames...)
}

// cruiser is a long white starship with a pointed nose, fins and a blue
// engine (facing left).
func cruiser() *pixelart.Image {
	im := pixelart.New(60, 17, magenta)
	ink := im.C(25, 30, 45)
	white := ramp(im, 225, 230, 240, 4)
	blue := im.C(60, 160, 255)
	pale := im.C(170, 230, 255)
	orange := im.C(255, 140, 40)

	im.Poly(white[2], 2, 9, 14, 5, 50, 5, 54, 7, 54, 11, 50, 13, 14, 13) // hull
	im.Poly(white[3], 6, 8, 14, 6, 48, 6, 48, 8)                         // light top
	im.Poly(white[1], 14, 12, 50, 12, 50, 13, 14, 13)                    // dark bottom
	im.Poly(white[1], 30, 5, 40, 0, 46, 0, 44, 5)                        // upper fin
	im.Poly(white[1], 30, 13, 40, 17, 46, 17, 44, 13)                    // lower fin
	im.Rect(16, 8, 10, 2, blue)                                          // the windows
	for x := 28; x < 46; x += 4 {
		im.Set(x, 8, pale)
	}
	im.Rect(54, 7, 3, 5, blue) // the engine
	im.Rect(57, 8, 2, 3, pale)
	im.Set(3, 9, orange)
	im.Outline(ink)
	return im
}

// warship is a heavy wedge of a warship, green-grey, with turrets and red
// lights (facing left).
func warship() *pixelart.Image {
	im := pixelart.New(50, 26, magenta)
	ink := im.C(15, 20, 15)
	hull := ramp(im, 90, 110, 85, 5)
	red := im.C(255, 50, 40)
	fire := im.C(255, 170, 40)

	im.Poly(hull[2], 2, 14, 16, 6, 42, 6, 46, 10, 46, 18, 42, 21, 16, 21) // hull
	im.Poly(hull[3], 6, 13, 16, 8, 42, 8, 42, 10, 16, 10)                 // light deck
	im.Poly(hull[1], 6, 16, 16, 19, 42, 19, 42, 21, 16, 21)               // dark keel
	im.Rect(24, 2, 10, 5, hull[2])                                        // the bridge
	im.Rect(24, 2, 10, 1, hull[4])
	im.Rect(26, 4, 6, 1, red)
	for _, x := range []int{14, 36} { // the turrets
		im.Rect(x, 4, 5, 3, hull[1])
		im.Line(x, 5, x-5, 4, hull[0])
	}
	for x := 18; x < 42; x += 5 {
		im.Set(x, 15, red)
	}
	im.Rect(46, 11, 3, 6, fire) // the engines
	im.Rect(48, 12, 2, 4, im.C(255, 240, 160))
	im.Outline(ink)
	return im
}

// mine is a round space mine with spikes and a light.
func mine() *pixelart.Image {
	im := pixelart.New(40, 40, magenta)
	ink := im.C(30, 10, 10)
	body := ramp(im, 170, 40, 40, 6)
	steel := ramp(im, 160, 160, 170, 3)
	for k := 0; k < 8; k++ { // the spikes
		a := float64(k) * math.Pi / 4
		x1, y1 := 20+19*math.Cos(a), 20+19*math.Sin(a)
		x0, y0 := 20+11*math.Cos(a), 20+11*math.Sin(a)
		im.Line(int(math.Round(x0)), int(math.Round(y0)), int(math.Round(x1)), int(math.Round(y1)), steel[1])
		im.Ball(x1, y1, 2, steel)
	}
	im.Ball(20, 20, 12, body)
	im.Rect(9, 19, 22, 2, body[1]) // the seam
	im.Ball(20, 14, 3, []uint8{im.C(255, 230, 80)})
	im.Set(19, 13, im.C(255, 255, 220))
	im.Outline(ink)
	return im
}

// fireAnt is a big red ant walking (facing left), its legs moving.
func fireAnt() *pixelart.Image {
	var frames []*pixelart.Image
	for ph := 0; ph < 2; ph++ {
		im := pixelart.New(50, 46, magenta)
		ink := im.C(35, 10, 5)
		red := ramp(im, 210, 60, 25, 6)
		leg := im.C(120, 35, 15)
		eye := im.C(20, 20, 20)

		// the legs: three on the far side, three near
		legs := [][4]int{{17, 30, 8, 44}, {24, 31, 24, 45}, {30, 30, 40, 44}}
		for i, l := range legs {
			sw := 3
			if (i+ph)%2 == 0 {
				sw = -3
			}
			mx, my := (l[0]+l[2])/2+sw, l[1]+6
			im.Line(l[0], l[1], mx, my, leg)
			im.Line(mx, my, l[2]+sw, l[3], leg)
			im.Line(mx+1, my, l[2]+sw+1, l[3], leg)
		}

		im.Ball(39, 24, 9, red)       // abdomen
		im.Ball(25, 26, 5, red)       // thorax
		im.Ball(12, 22, 7, red)       // head
		im.Rect(17, 25, 4, 3, red[2]) // the waist
		im.Ball(9, 20, 1.8, []uint8{eye})
		im.Set(8, 19, im.C(200, 200, 200))
		// the mandibles and the antennas
		im.Line(5, 26, 1, 28-ph, red[1])
		im.Line(6, 27, 2, 30-ph, red[1])
		im.Line(12, 15, 7, 6+ph, red[1])
		im.Line(7, 6+ph, 2, 5+ph, red[1])
		im.Line(14, 15, 13, 5, red[1])
		im.Line(13, 5, 9, 2, red[1])
		for x := 34; x < 46; x += 4 { // the stripes of the abdomen
			im.Line(x, 18, x+1, 30, red[1])
		}
		im.Outline(ink)
		frames = append(frames, im)
	}
	return pixelart.Join(frames...)
}

// title reads the title of the C source, decompresses it and clears the
// logo of the shop (x 10..91, y 7..27).
func title(root string) (pal, img []byte) {
	src, err := os.ReadFile(filepath.Join(root, "PicoPad/GAME/PICTOR/img/title.cpp"))
	if err != nil {
		log.Fatal(err)
	}
	pal = array(src, "TitleImg_Pal", 2)
	rle := array(src, "TitleImg", 1)
	img = make([]byte, 0, 320*240)
	for i := 0; len(img) < 320*240; {
		c := int(rle[i])
		i++
		if c >= 128 {
			for n := c - 128 + 3; n > 0; n-- {
				img = append(img, rle[i])
			}
			i++
		} else {
			img = append(img, rle[i:i+c+1]...)
			i += c + 1
		}
	}
	img = img[:320*240]
	black := byte(0)
	for e := 0; e < len(pal)/2; e++ {
		if pal[2*e] == 0 && pal[2*e+1] == 0 {
			black = byte(e)
			break
		}
	}
	for y := 7; y <= 27; y++ {
		for x := 10; x <= 91; x++ {
			img[y*320+x] = black
		}
	}
	return pal, img
}

// array returns the values of the C array name (size bytes each, little
// endian).
func array(src []byte, name string, size int) []byte {
	re := regexp.MustCompile(`(?s)const\s+u(?:8|16)\s+` + name + `\s*\[[^\]]*\][^=]*=\s*\{(.*?)\}\s*;`)
	m := re.FindSubmatch(src)
	if m == nil {
		log.Fatalf("no array %s", name)
	}
	var out []byte
	for _, f := range strings.FieldsFunc(string(m[1]), func(r rune) bool { return r == ',' || r <= ' ' }) {
		v, err := strconv.ParseUint(f, 0, 16)
		if err != nil {
			log.Fatal(err)
		}
		out = append(out, byte(v))
		if size == 2 {
			out = append(out, byte(v>>8))
		}
	}
	return out
}
