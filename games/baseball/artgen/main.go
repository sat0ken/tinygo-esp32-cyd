// Command artgen draws the pictures of package baseball: the ballpark seen
// from behind the catcher (the batting view), the field from above (the
// fielding view), and the players (pixel art drawn here). It writes art.go,
// the backgrounds in data/*.dat and previews in art/.
//
//	go generate ./games/baseball   (go run ./artgen in games/baseball)
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"math/rand"
	"os"
	"path/filepath"

	"github.com/sat0ken/tinygo-cyd/internal/pixelart"
	"github.com/sat0ken/tinygo-cyd/picopad"
)

// key is the transparent colour of the sprites.
const key = picopad.ColMagenta

// The stand-in colours of the team, replaced by each team's colours when
// the game starts.
var (
	teamCol  = picopad.RGB(16, 32, 232)
	teamDark = picopad.RGB(8, 16, 120)
)

func main() {
	for _, d := range []string{"art", "data"} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			log.Fatal(err)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by artgen. DO NOT EDIT.\n\npackage baseball\n\nimport (\n\t_ \"embed\"\n\n\t\"github.com/sat0ken/tinygo-cyd/picopad\"\n)\n")
	fmt.Fprintf(&b, "\n// The stand-in colours of the team in the sprites.\nconst (\n\tstandInTeam = picopad.Color(%#04x)\n\tstandInDark = picopad.Color(%#04x)\n)\n", teamCol, teamDark)

	pics := []struct {
		name, about string
		w, h        int
		img         *pixelart.Image
	}{
		{"batBg", "the ballpark from behind the catcher, with the strike zone", 320, 240, batView()},
		{"fieldBg", "the field from above (1.75 ft a pixel, home plate at 160, 232)", 320, 240, fieldView()},
		{"batter", "a right-handed batter from behind: the stance, the swing, the follow-through; then the same for a left-hander (6 x 48 x 64, side by side)", 48, 64, batters()},
		{"pitcher", "the pitcher: set, the leg kick, the release (3 x 24 x 32, side by side)", 24, 32, pitchers()},
		{"catcher", "the catcher from behind", 40, 34, catcher()},
		{"fielder", "a fielder and a runner from above (2 x 11 x 11)", 11, 11, tops()},
	}
	for _, p := range pics {
		im := p.img
		fmt.Fprintf(&b, "\n// %s\n//\n// format: 8-bit paletted pixel graphics\n// image width: %d pixels\n// image height: %d lines\n// image pitch: %d bytes\n",
			p.about, im.W, im.H, im.W)
		fmt.Fprintf(&b, "const (\n\t%sW = %d\n\t%sH = %d\n)\n\n", p.name, p.w, p.name, p.h)
		fmt.Fprintf(&b, "const %sImgPal = %s\n\n", p.name, pixelart.Literal(im.PalData()))
		if len(im.Pix) >= 1024 {
			file := p.name + "Img.dat"
			if err := os.WriteFile(filepath.Join("data", file), im.Data(), 0o644); err != nil {
				log.Fatal(err)
			}
			fmt.Fprintf(&b, "//go:embed data/%s\nvar %sImg string\n", file, p.name)
		} else {
			fmt.Fprintf(&b, "const %sImg = %s\n", p.name, pixelart.Literal(im.Data()))
		}
		scale := 3
		if im.W*im.H > 20000 {
			scale = 2
		}
		if err := im.WritePNG(filepath.Join("art", p.name+".png"), scale); err != nil {
			log.Fatal(err)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("art.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

type rgb struct{ r, g, b float64 }

func (c rgb) mix(d rgb, t float64) rgb {
	return rgb{c.r + (d.r-c.r)*t, c.g + (d.g-c.g)*t, c.b + (d.b-c.b)*t}
}

func (c rgb) in(im *pixelart.Image) uint8 {
	cl := func(v float64) uint8 { return uint8(math.Max(0, math.Min(255, math.Round(v)))) }
	return im.C(cl(c.r), cl(c.g), cl(c.b))
}

// The field (feet: home plate at 0, 0; x to the right, y to center field).

func fenceDist(x, y float64) float64 {
	dir := math.Atan2(x, y)
	return 330 + 70*math.Cos(2*dir)
}

// The kinds of ground.
const (
	gGrass = iota
	gGrass2
	gFoul
	gDirt
	gMound
	gLine
	gBase
	gWall
	gStands
)

// ground returns what is at x, y and how far the point is from the fence
// (for the wall's top).
func ground(x, y float64) int {
	d := math.Hypot(x, y)
	dir := math.Atan2(x, y) * 180 / math.Pi
	fd := fenceDist(x, y)
	if d > fd+9 {
		return gStands
	}
	if d > fd {
		return gWall
	}
	// the bases
	for _, b := range [][2]float64{{63.64, 63.64}, {0, 127.28}, {-63.64, 63.64}} {
		if math.Abs(x-b[0]) < 1.6 && math.Abs(y-b[1]) < 1.6 {
			return gBase
		}
	}
	// the foul lines
	if y > 0 && math.Abs(math.Abs(x)-y) < 0.9+d*0.004 {
		return gLine
	}
	fair := dir >= -45 && dir <= 45
	if math.Hypot(x, y-60.5) < 9 {
		return gMound
	}
	if d < 13 {
		return gDirt // around home plate
	}
	if fair {
		inner := math.Abs(x)+math.Abs(y-63.64) < 63.64-4 // the infield grass
		paths := math.Abs(math.Abs(x)-y) < 3 && y < 70 || math.Abs(math.Abs(x)+y-127.28) < 3 && y > 60
		if (math.Hypot(x, y-60.5) < 95 && !inner) || paths {
			return gDirt
		}
		if int(math.Floor(y/16))%2 == 0 {
			return gGrass
		}
		return gGrass2
	}
	return gFoul
}

var groundCol = [...]rgb{
	gGrass:  {46, 150, 60},
	gGrass2: {60, 168, 72},
	gFoul:   {40, 128, 54},
	gDirt:   {196, 150, 96},
	gMound:  {214, 170, 116},
	gLine:   {250, 250, 250},
	gBase:   {255, 255, 255},
	gWall:   {24, 82, 54},
	gStands: {54, 58, 90},
}

// crowd colours a pixel of the stands.
func crowd(im *pixelart.Image, rnd *rand.Rand, x, y int, base rgb) uint8 {
	if (x+y*3)%4 == 0 && rnd.Intn(3) > 0 {
		cols := []rgb{{230, 200, 170}, {240, 80, 70}, {80, 120, 230}, {250, 240, 220}, {250, 210, 60}, {120, 200, 120}}
		return cols[rnd.Intn(len(cols))].in(im)
	}
	return base.in(im)
}

// batView is the ballpark from behind the catcher: a perspective in which
// home plate is at y 222, the mound at 100, second base at 75, and the
// horizon at 40.
func batView() *pixelart.Image {
	const w, h = 320, 240
	im := pixelart.New(w, h, key)
	rnd := rand.New(rand.NewSource(1))
	const yh, k, d0, kx = 40.0, 5415.0, 29.75, 132.0
	for sy := 0; sy < h; sy++ {
		for sx := 0; sx < w; sx++ {
			var c uint8
			if float64(sy) <= yh+3 {
				c = crowd(im, rnd, sx, sy, rgb{40, 44, 76}.mix(rgb{70, 74, 110}, float64(sy)/yh))
			} else {
				y := k/(float64(sy)+0.5-yh) - d0
				x := (float64(sx) + 0.5 - 160) * (y + d0) / kx
				g := ground(x, y)
				switch g {
				case gStands:
					c = crowd(im, rnd, sx, sy, rgb{54, 58, 90})
				case gWall:
					c = groundCol[gWall].in(im)
					if math.Hypot(x, y) > fenceDist(x, y)+7 {
						c = im.C(250, 210, 40) // the yellow top
					}
				default:
					c = groundCol[g].in(im)
				}
			}
			im.Set(sx, sy, c)
		}
	}

	// home plate, the batter's boxes, the strike zone
	white := im.C(250, 250, 250)
	plate := im.C(240, 240, 236)
	im.Poly(plate, 136, 208, 184, 208, 184, 214, 160, 222, 136, 214)
	chalk := im.C(236, 232, 220)
	for _, bx := range []int{86, 192} {
		frame(im, bx, 196, 42, 32, chalk)
	}
	const zx, zy, zw, zh = 134, 120, 52, 60
	grid := im.C(210, 210, 210)
	for i := 1; i < 3; i++ {
		for y := zy; y < zy+zh; y += 2 {
			im.Set(zx+i*zw/3, y, grid)
		}
		for x := zx; x < zx+zw; x += 2 {
			im.Set(x, zy+i*zh/3, grid)
		}
	}
	frame(im, zx, zy, zw, zh, white)
	return im
}

// frame draws the outline of a rectangle.
func frame(im *pixelart.Image, x, y, w, h int, c uint8) {
	im.Rect(x, y, w, 1, c)
	im.Rect(x, y+h-1, w, 1, c)
	im.Rect(x, y, 1, h, c)
	im.Rect(x+w-1, y, 1, h, c)
}

// fieldView is the field from above.
func fieldView() *pixelart.Image {
	const w, h = 320, 240
	im := pixelart.New(w, h, key)
	rnd := rand.New(rand.NewSource(2))
	for sy := 0; sy < h; sy++ {
		for sx := 0; sx < w; sx++ {
			x := (float64(sx) + 0.5 - 160) * 1.75
			y := (232 - float64(sy) - 0.5) * 1.75
			var c uint8
			switch g := ground(x, y); g {
			case gStands:
				c = crowd(im, rnd, sx, sy, rgb{54, 58, 90})
			case gWall:
				c = im.C(250, 210, 40)
			default:
				c = groundCol[g].in(im)
			}
			im.Set(sx, sy, c)
		}
	}
	// home plate
	im.Poly(im.C(255, 255, 255), 157, 231, 163, 231, 163, 233, 160, 235, 157, 233)
	return im
}

// person colours.
type colours struct {
	team, dark, skin, skinD, white, gray, black, bat, batD, glove uint8
}

func paints(im *pixelart.Image) colours {
	return colours{
		team: im.Col(teamCol), dark: im.Col(teamDark),
		skin: im.C(246, 196, 150), skinD: im.C(214, 156, 112),
		white: im.C(246, 246, 246), gray: im.C(176, 180, 190), black: im.C(30, 30, 40),
		bat: im.C(224, 184, 120), batD: im.C(170, 124, 70), glove: im.C(150, 90, 40),
	}
}

// batter draws a right-handed batter from behind, in phase 0 (stance), 1
// (swing) or 2 (follow-through): a big helmet, the team's jersey, white
// trousers.
func batter(phase int) *pixelart.Image {
	im := pixelart.New(48, 64, key)
	c := paints(im)
	// the legs
	im.Poly(c.white, 14, 44, 22, 44, 21, 58, 13, 58)
	im.Poly(c.white, 26, 44, 34, 44, 37, 58, 29, 58)
	im.Rect(12, 58, 10, 4, c.black)
	im.Rect(29, 58, 10, 4, c.black)
	im.Rect(14, 44, 20, 3, c.gray) // the belt
	// the body (the back of the jersey)
	im.Poly(c.white, 12, 26, 36, 26, 34, 45, 14, 45)
	im.Rect(21, 29, 6, 10, c.team) // the number
	im.Rect(12, 26, 24, 2, c.team)
	// the head: a big helmet
	im.Ellipse(24, 16, 11, 11, c.dark)
	im.Ellipse(24, 15, 10, 9.5, c.team)
	im.Rect(15, 20, 18, 4, c.dark)
	im.Ellipse(33, 21, 3, 3, c.skin) // an ear, the face turned to the pitcher
	switch phase {
	case 0: // the stance: the hands at the back shoulder, the bat up
		im.Ellipse(11, 28, 4, 4, c.skin)
		im.Line(10, 27, 4, 6, c.batD)
		im.Line(11, 27, 5, 6, c.bat)
		im.Line(12, 27, 6, 6, c.bat)
	case 1: // the swing: the bat across the plate
		im.Ellipse(36, 34, 4, 4, c.skin)
		im.Rect(36, 32, 12, 3, c.bat)
		im.Rect(36, 35, 12, 1, c.batD)
	case 2: // the follow-through: the bat over the front shoulder
		im.Ellipse(36, 26, 4, 4, c.skin)
		im.Line(36, 25, 46, 8, c.bat)
		im.Line(37, 25, 47, 9, c.batD)
		im.Line(35, 25, 45, 8, c.bat)
	}
	im.Outline(im.C(20, 20, 30))
	return im
}

func batters() *pixelart.Image {
	var frames []*pixelart.Image
	for p := 0; p < 3; p++ {
		frames = append(frames, batter(p))
	}
	for p := 0; p < 3; p++ {
		f := batter(p)
		f.FlipX()
		frames = append(frames, f)
	}
	return pixelart.Join(frames...)
}

// pitcher draws the pitcher facing us: 0 set, 1 the leg kick, 2 the release.
func pitcher(phase int) *pixelart.Image {
	im := pixelart.New(24, 32, key)
	c := paints(im)
	// legs
	switch phase {
	case 1:
		im.Rect(9, 21, 3, 9, c.white)
		im.Poly(c.white, 12, 20, 19, 17, 20, 20, 13, 23)
		im.Rect(8, 29, 4, 2, c.black)
	default:
		im.Rect(8, 21, 3, 9, c.white)
		im.Rect(13, 21, 3, 9, c.white)
		im.Rect(7, 29, 4, 2, c.black)
		im.Rect(13, 29, 4, 2, c.black)
	}
	// body
	im.Poly(c.white, 7, 12, 17, 12, 16, 22, 8, 22)
	im.Rect(10, 14, 4, 4, c.team)
	// head with the cap
	im.Ellipse(12, 7, 6, 6, c.skin)
	im.Rect(6, 1, 12, 4, c.team)
	im.Ellipse(12, 3, 6, 3, c.team)
	im.Rect(8, 5, 8, 1, c.dark)
	im.Set(10, 8, c.black)
	im.Set(14, 8, c.black)
	switch phase {
	case 0: // the hands together at the chest
		im.Ellipse(12, 15, 3, 2.5, c.glove)
	case 1:
		im.Ellipse(13, 13, 3, 2.5, c.glove)
	case 2: // the throwing arm over the head, the glove out
		im.Rect(3, 3, 3, 10, c.white)
		im.Ellipse(4, 3, 2, 2, c.skin)
		im.Ellipse(20, 15, 3, 2.5, c.glove)
	}
	im.Outline(im.C(20, 20, 30))
	return im
}

func pitchers() *pixelart.Image {
	return pixelart.Join(pitcher(0), pitcher(1), pitcher(2))
}

// catcher is the catcher crouching, from behind.
func catcher() *pixelart.Image {
	im := pixelart.New(40, 34, key)
	c := paints(im)
	gear := im.C(40, 44, 60)
	im.Ellipse(20, 25, 15, 9, c.white) // the crouched legs
	im.Rect(6, 26, 7, 8, gear)         // the shin guards
	im.Rect(27, 26, 7, 8, gear)
	im.Poly(c.white, 9, 12, 31, 12, 33, 26, 7, 26) // the back
	im.Rect(17, 14, 6, 8, c.team)
	im.Ellipse(20, 8, 8, 7, c.dark) // the helmet
	im.Ellipse(20, 7, 7, 6, c.team)
	im.Ellipse(33, 12, 5, 4.5, c.glove) // the mitt
	im.Outline(im.C(20, 20, 30))
	return im
}

// tops are a fielder (a cap) and a runner (a helmet) seen from above.
func tops() *pixelart.Image {
	f := pixelart.New(11, 11, key)
	c := paints(f)
	f.Ellipse(5.5, 6.5, 5, 3.5, c.white) // the shoulders
	f.Ellipse(5.5, 5.5, 3.2, 3.2, c.team)
	f.Rect(4, 2, 3, 2, c.dark) // the peak
	f.Outline(f.C(20, 20, 30))
	r := pixelart.New(11, 11, key)
	c = paints(r)
	r.Ellipse(5.5, 6.5, 5, 3.5, c.white)
	r.Ellipse(5.5, 5.5, 3.5, 3.5, c.dark)
	r.Ellipse(5.5, 5, 2.4, 2.4, c.team)
	r.Outline(r.C(20, 20, 30))
	return pixelart.Join(f, r)
}
